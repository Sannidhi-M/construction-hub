import { Badge, Button } from "@modules/common/components/ui"
import { useMemo } from "react"

import Thumbnail from "@modules/products/components/thumbnail"
import LocalizedClientLink from "@modules/common/components/localized-client-link"
import { convertToLocale } from "@lib/util/money"
import { HttpTypes } from "@medusajs/types"
import {
  CustomerOrderStatus,
  getCustomerOrderStatus,
} from "@lib/util/order-status"

type OrderCardProps = {
  order: HttpTypes.StoreOrder
}

const STATUS_BADGE_COLOR: Record<
  CustomerOrderStatus,
  "green" | "red" | "blue" | "orange" | "grey" | "purple"
> = {
  "Payment Pending": "orange",
  "Payment Verification Pending": "orange",
  "Order Confirmed": "blue",
  "Order Processing": "blue",
  "Out for Delivery": "purple",
  Delivered: "green",
  Cancelled: "red",
}

const OrderCard = ({ order }: OrderCardProps) => {
  const customerStatus = getCustomerOrderStatus(
    order,
    !!order.metadata?.payment_customer_confirmed,
    order.metadata?.payment_method === "cod" ? "cod" : undefined
  )

  const numberOfLines = useMemo(() => {
    return (
      order.items?.reduce((acc, item) => {
        return acc + item.quantity
      }, 0) ?? 0
    )
  }, [order])

  const numberOfProducts = useMemo(() => {
    return order.items?.length ?? 0
  }, [order])

  return (
    <div className="bg-white flex flex-col" data-testid="order-card">
      <div className="flex items-center gap-x-3 mb-1">
        <span className="uppercase text-large-semi">
          #<span data-testid="order-display-id">{order.display_id}</span>
        </span>
        <Badge
          color={STATUS_BADGE_COLOR[customerStatus]}
          data-testid="order-customer-status"
        >
          {customerStatus}
        </Badge>
      </div>
      <div className="flex items-center divide-x divide-gray-200 text-small-regular text-ui-fg-base">
        <span className="pr-2" data-testid="order-created-at">
          {new Date(order.created_at).toDateString()}
        </span>
        <span className="px-2" data-testid="order-amount">
          {convertToLocale({
            amount: order.total,
            currency_code: order.currency_code,
          })}
        </span>
        <span className="pl-2">{`${numberOfLines} ${
          numberOfLines > 1 ? "items" : "item"
        }`}</span>
      </div>
      <div className="grid grid-cols-2 small:grid-cols-4 gap-4 my-4">
        {order.items?.slice(0, 3).map((i) => {
          return (
            <div
              key={i.id}
              className="flex flex-col gap-y-2"
              data-testid="order-item"
            >
              <Thumbnail thumbnail={i.thumbnail} images={i.product?.images} size="full" />
              <div className="flex items-center text-small-regular text-ui-fg-base">
                <span
                  className="text-ui-fg-base font-semibold"
                  data-testid="item-title"
                >
                  {i.title}
                </span>
                <span className="ml-2">x</span>
                <span data-testid="item-quantity">{i.quantity}</span>
              </div>
            </div>
          )
        })}
        {numberOfProducts > 4 && (
          <div className="w-full h-full flex flex-col items-center justify-center">
            <span className="text-small-regular text-ui-fg-base">
              + {numberOfLines - 4}
            </span>
            <span className="text-small-regular text-ui-fg-base">more</span>
          </div>
        )}
      </div>
      <div className="flex justify-end">
        <LocalizedClientLink href={`/account/orders/details/${order.id}`}>
          <Button data-testid="order-details-link" variant="secondary">
            See details
          </Button>
        </LocalizedClientLink>
      </div>
    </div>
  )
}

export default OrderCard
